/* ── Helper Math Functions for Road Travel ───────────────────── */
function _calcBearing(from, to) {
  const dLng = (to[1] - from[1]) * Math.PI / 180;
  const lat1 = from[0] * Math.PI / 180;
  const lat2 = to[0] * Math.PI / 180;
  const x = Math.sin(dLng) * Math.cos(lat2);
  const y = Math.cos(lat1) * Math.sin(lat2) - Math.sin(lat1) * Math.cos(lat2) * Math.cos(dLng);
  return (Math.atan2(x, y) * 180 / Math.PI + 360) % 360;
}

function _calcDistKm(from, to) {
  const R = 6371;
  const dLat = (to[0] - from[0]) * Math.PI / 180;
  const dLng = (to[1] - from[1]) * Math.PI / 180;
  const a = Math.sin(dLat / 2) ** 2 + Math.cos(from[0] * Math.PI / 180) * Math.cos(to[0] * Math.PI / 180) * Math.sin(dLng / 2) ** 2;
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

/* ── Animate Vehicles Along Real Road Coordinates (Start to Dest) ── */
function animateVehicles(map, vehicleMarkers) {
  map = map || MapEngine.map;
  vehicleMarkers = vehicleMarkers || MapEngine.vehicleMarkers || {};
  if (!map) return;

  const animStates = {};
  const vehicleTrails = {};

  Object.entries(vehicleMarkers).forEach(([id, marker], idx) => {
    const vData = (VEHICLE_DATA.find(v => v.id === id) || { id, speed: 45 });
    if (vData.status === 'blocked') return;

    let assignedRoad = ROAD_DATA.find(r => r.id === vData.roadId);
    if (!assignedRoad || !assignedRoad.coords || assignedRoad.coords.length < 2) {
      assignedRoad = ROAD_DATA[idx % ROAD_DATA.length];
    }
    if (!assignedRoad || !assignedRoad.coords || assignedRoad.coords.length < 2) return;

    const coords = assignedRoad.coords;
    const curPos = marker.getLatLng();
    let bestIdx = 0;
    let minD = Infinity;
    coords.forEach((pt, pIdx) => {
      const d = Math.hypot(pt[0] - curPos.lat, pt[1] - curPos.lng);
      if (d < minD) { minD = d; bestIdx = pIdx; }
    });

    animStates[id] = {
      coords: coords,
      roadId: assignedRoad.id,
      index: bestIdx,
      progress: 0,
      direction: 1,
      speed: (vData.speed || 45),
      trail: []
    };

    const trailLine = L.polyline([], {
      color: vData.status === 'delayed' ? '#ff9500' : '#00ff88',
      weight: 3,
      opacity: 0.6,
      interactive: false,
      lineCap: 'round',
      lineJoin: 'round'
    }).addTo(map);

    vehicleTrails[id] = trailLine;
  });

  let lastTime = performance.now();

  function step(now) {
    const dt = Math.min((now - lastTime) / 1000, 0.08);
    lastTime = now;

    Object.entries(vehicleMarkers).forEach(([id, marker]) => {
      const state = animStates[id];
      if (!state) return;

      const coords = state.coords;
      const curIdx = state.index;
      const nextIdx = curIdx + state.direction;

      if (nextIdx < 0 || nextIdx >= coords.length) {
        state.direction *= -1;
        state.progress = 0;
        return;
      }

      const from = coords[curIdx];
      const to = coords[nextIdx];
      const segKm = _calcDistKm(from, to);
      const fracPerSec = segKm > 0.0001 ? (state.speed / 3600) / segKm : 1;

      state.progress += fracPerSec * dt * 2.5;

      while (state.progress >= 1.0) {
        state.progress -= 1.0;
        state.index += state.direction;
        if (state.index + state.direction < 0 || state.index + state.direction >= coords.length) {
          state.direction *= -1;
          state.progress = 0;
          break;
        }
      }

      const pFrom = coords[state.index];
      const pTo = coords[Math.min(Math.max(0, state.index + state.direction), coords.length - 1)];
      const lat = pFrom[0] + (pTo[0] - pFrom[0]) * state.progress;
      const lng = pFrom[1] + (pTo[1] - pFrom[1]) * state.progress;
      const bearing = _calcBearing(pFrom, pTo);

      marker.setLatLng([lat, lng]);

      const el = marker.getElement();
      if (el) {
        const rotWrap = el.querySelector('.v-rot-wrapper');
        if (rotWrap) rotWrap.style.transform = `rotate(${bearing}deg)`;
      }

      state.trail.push([lat, lng]);
      if (state.trail.length > 20) state.trail.shift();
      if (vehicleTrails[id]) {
        vehicleTrails[id].setLatLngs(state.trail);
      }
    });

    requestAnimationFrame(step);
  }

  requestAnimationFrame(step);
}


/* ── Flood Zone ─────────────────────────────────────────────── */
function addFloodZone(map, center, radius = 0.08) {
  map = map || MapEngine.map;
  if (!map) return null;
  // Animated flood polygon
  const points = [];
  for (let i = 0; i <= 32; i++) {
    const angle = (i / 32) * Math.PI * 2;
    const r = radius * (0.85 + Math.random() * 0.3);
    points.push([
      center[0] + Math.cos(angle) * r,
      center[1] + Math.sin(angle) * r * 1.5
    ]);
  }

  const flood = L.polygon(points, {
    color: '#4facfe',
    weight: 2,
    opacity: 0.7,
    fillColor: '#4facfe',
    fillOpacity: 0.15,
    dashArray: '6,4',
    className: 'flood-zone'
  }).addTo(map);

  flood.bindPopup(`
    <div style="font-family:'Outfit',sans-serif;">
      <div style="font-weight:800;color:#4facfe;margin-bottom:4px;">🌊 FLOOD ZONE</div>
      <div style="font-size:12px;color:#b4d2f0;">Active flooding detected in this area.<br>Roads may be submerged.</div>
    </div>
  `);

  return flood;
}

