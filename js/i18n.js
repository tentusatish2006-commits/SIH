  // Core Engine
  const SmartRouteI18n = {
    languages: LANGUAGES,

    getLanguageInfo(code) {
      code = code || this.getLanguage();
      return LANGUAGES.find(l => l.code === code) || LANGUAGES[0];
    },

    _currentLang: null,

    getLanguage() {
      if (this._currentLang) return this._currentLang;
      try {
        const saved = localStorage.getItem('sr_language');
        if (saved && LANGUAGES.some(l => l.code === saved)) {
          this._currentLang = saved;
          return saved;
        }
      } catch (e) {}
      return 'en';
    },

    t(key, langCode, fallback) {
      const current = langCode || this._currentLang || this.getLanguage();
      const dict = TRANSLATIONS[current] || TRANSLATIONS.en;
      if (dict && dict[key]) return dict[key];
      if (TRANSLATIONS.en && TRANSLATIONS.en[key]) return TRANSLATIONS.en[key];
      return fallback || key;
    },

    setLanguage(code) {
      const lang = LANGUAGES.find(l => l.code === code);
      if (!lang) return false;

      this._currentLang = code;
      try {
        localStorage.setItem('sr_language', code);
      } catch (e) {}

      this.applyLanguage(code);

      // Dispatch event
      try {
        window.dispatchEvent(new CustomEvent('smartroute:language-changed', {
          detail: { language: code, info: lang }
        }));
      } catch(e) {}

      return true;
    },

    applyLanguage(code) {
      code = code || this.getLanguage();
      this._currentLang = code;
      document.documentElement.lang = code;
      try {
        localStorage.setItem('sr_language', code);
      } catch (e) {}

      // 1. Elements with data-i18n attribute
      document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const translated = this.t(key, code);
        if (translated && translated !== key) {
          if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
            el.value = translated;
          } else {
            el.textContent = translated;
          }
        }
      });

      // 2. Elements with data-i18n-placeholder
      document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        const translated = this.t(key, code);
        if (translated && translated !== key) el.setAttribute('placeholder', translated);
      });

      // 3. Dynamic Sidebar translations (if sidebar is present)
      const sidebarNav = document.getElementById('sidebar-nav');
      if (sidebarNav) {
        sidebarNav.querySelectorAll('.sidebar-section-label').forEach(label => {
          const key = label.getAttribute('data-i18n') || `nav_sec_${label.textContent.trim().toLowerCase()}`;
          const translated = this.t(key, code);
          if (translated && translated !== key) label.textContent = translated;
        });

        sidebarNav.querySelectorAll('.nav-item').forEach(item => {
          const labelSpan = item.querySelector('.nav-label');
          const key = labelSpan ? (labelSpan.getAttribute('data-i18n') || `nav_${(item.getAttribute('href') || '').replace('.html', '').replace(/-/g, '_')}`) : null;
          if (key) {
            const translated = this.t(key, code);
            if (labelSpan && translated && translated !== key) {
              labelSpan.textContent = translated;
            }
          }
        });
      }

      // 4. Update settings nav pills if present
      const navPills = document.querySelectorAll('.settings-nav .nav-pill');
      navPills.forEach(pill => {
        const key = pill.getAttribute('data-i18n');
        if (key) {
          const translated = this.t(key, code);
          if (translated && translated !== key) pill.textContent = translated;
        } else {
          const onclick = pill.getAttribute('onclick') || '';
          const match = onclick.match(/'([^']+)'/);
          if (match && match[1]) {
            const k = `tab_${match[1]}`;
            const translated = this.t(k, code);
            if (translated && translated !== k) pill.textContent = translated;
          }
        }
      });
    }
  };

  // Expose globally
  window.SmartRouteI18n = SmartRouteI18n;

  // Auto-apply on DOMContentLoaded
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => SmartRouteI18n.applyLanguage());
  } else {
    SmartRouteI18n.applyLanguage();
  }

