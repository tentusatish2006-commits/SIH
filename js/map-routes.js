  _loop(timestamp) {
    if (!this.running || this.paused) return;
    const dt = this.lastTime ? Math.min((timestamp - this.lastTime) / 1000, 0.08) : 0.016;
    this.lastTime = timestamp;
    this.tickCount++;

    this.vehicles.forEach(v => this._stepVehicle(v, dt));

    if (this.tickCount % 30 === 0) this._updateDashboard();
    this.animFrameId = requestAnimationFrame(ts => this._loop(ts));
  },

  _stepVehicle(v, dt) {
    if (!v.marker || v.status === 'arrived') return;

    if (v.paused) {
      v.pauseFrames--;
      if (v.pauseFrames <= 0) {
        v.paused = false;
        if (v.pendingReroute) {
          v.pendingReroute = false;
          this._executeReroute(v);
        }
      }
      return;
    }

    const coords = v.currentRouteCoords;
    if (!coords || v.routeIndex >= coords.length - 1) {
      v.status = 'arrived';
      this._showAlert(`✅ ${v.id} ARRIVED`, `Vehicle successfully reached destination: ${v.dest}`, 'success');
      return;
    }

    if (v.rerouteAtIndex > 0 && v.routeIndex >= v.rerouteAtIndex && !v.rerouted && !v.pendingReroute) {
      v.paused = true;
      v.pauseFrames = 130;
      v.pendingReroute = true;
      v.status = 'rerouting';
      this._triggerRerouteAlert(v);
      this._showBlockedSegment();
    }

    const from = coords[v.routeIndex];
    const to = coords[v.routeIndex + 1];
    const segKm = _segKm(from, to);
    const fracPerSec = segKm > 0.0001 ? (v.speed / 3600) / segKm : 1;
    v.progress += fracPerSec * dt * 2.2;

    while (v.progress >= 1.0 && v.routeIndex < coords.length - 2) {
      v.progress -= 1.0;
      v.routeIndex++;
    }
    v.progress = Math.min(v.progress, 1.0);
    v._progressPct = v.routeIndex / (coords.length - 1);

    const cFrom = coords[v.routeIndex];
    const cTo = coords[Math.min(v.routeIndex + 1, coords.length - 1)];
    const pos = _interpLL(cFrom, cTo, v.progress);
    const bearing = _getBearing(cFrom, cTo);

    v.marker.setLatLng(pos);
    this._updateVehicleIconRotation(v, bearing);

    v.trail.push([...pos]);
    if (v.trail.length > 24) v.trail.shift();
    if (this.trailLayers[v.id]) {
      this.trailLayers[v.id].setLatLngs(v.trail);
    }

    const panel = document.getElementById('vehicle-info-panel');
    if (panel && panel.dataset.vehicleId === v.id && panel.style.display !== 'none') {
      this._populateVehiclePanel(v, { lat: pos[0], lng: pos[1] });
    }
  },

