  _showVehiclePanel(v) {
    const panel = document.getElementById('vehicle-info-panel');
    if (!panel) return;
    panel.dataset.vehicleId = v.id;
    this._populateVehiclePanel(v, v.marker ? v.marker.getLatLng() : null);
    panel.style.display = 'block';
    panel.style.opacity = '1';

    if (v.marker && this.map) {
      this.map.flyTo(v.marker.getLatLng(), 11, { duration: 1.5 });
    }
  },

  _populateVehiclePanel(v, pos) {
    const ri = DEMO_ROUTES[v.routeKey] || {};
    const total = v.currentRouteCoords.length - 1;
    const pct = total > 0 ? v.routeIndex / total : 0;
    const distNum = parseFloat((ri.distance || '0').replace(/[^0-9.]/g, ''));
    const kmLeft = Math.max(0, distNum * (1 - pct));
    const hL = Math.floor(kmLeft / (v.speed || 1));
    const mL = Math.round((kmLeft / (v.speed || 1) - hL) * 60);

    const se = (id, val) => { const e = document.getElementById(id); if (e) e.textContent = val; };
    const sc = (id, c) => { const e = document.getElementById(id); if (e) e.style.color = c; };

    se('vip-id', v.id);
    se('vip-type', `${v.type} ${v.typeLabel}`);
    se('vip-cargo', v.cargo);
    se('vip-name', v.name);
    se('vip-location', pos ? `${Number(pos.lat).toFixed(4)}°N, ${Number(pos.lng).toFixed(4)}°E` : 'Tracking GPS...');
    se('vip-dest', v.dest || ri.dest || '—');
    se('vip-route', v.rerouted ? '🟡 ALTERNATE ROUTE — Via Silchar-Jiribam' : `🟢 ${v.roadName}`);
    se('vip-speed', v.paused ? '0 km/h (Halted for Reroute)' : `${v.speed} km/h`);
    se('vip-eta', isNaN(hL) ? '—' : `~${hL}h ${mL}m (${kmLeft.toFixed(1)} km left)`);
    se('vip-risk', v.riskLevel);
    sc('vip-risk', v.riskLevel === 'CRITICAL' ? '#ff3b3b' : v.riskLevel === 'HIGH' ? '#ff6b00' : v.riskLevel === 'MODERATE' ? '#ff9500' : '#00ff88');

    const statusTxt = v.status === 'rerouting' ? 'REROUTING OVERWAY' : (v.status || 'ON ROUTE').toUpperCase().replace(/-/g, ' ');
    se('vip-status', statusTxt);
    sc('vip-status', v.status === 'on-route' ? '#00ff88' : v.status === 'delayed' ? '#ff9500' : v.status === 'rerouting' ? '#ffcc00' : '#ff3b3b');

    const bar = document.getElementById('vip-progress-bar');
    if (bar) bar.style.width = Math.round(pct * 100) + '%';
    const pEl = document.getElementById('vip-progress-pct');
    if (pEl) pEl.textContent = `${Math.round(pct * 100)}% route complete (${(distNum * pct).toFixed(1)} / ${distNum} km)`;
  },

  _showAlert(title, message, type) {
    const el = document.getElementById('live-alert-box');
    if (!el) return;
    const cfg = {
      critical: { border: '#ff3b3b', bg: 'rgba(28, 0, 0, 0.96)', icon: '🚨' },
      info:     { border: '#00d4ff', bg: 'rgba(0, 14, 30, 0.96)', icon: 'ℹ️' },
      success:  { border: '#00ff88', bg: 'rgba(0, 20, 10, 0.96)', icon: '✅' },
      warning:  { border: '#ff9500', bg: 'rgba(24, 12, 0, 0.96)', icon: '⚠️' }
    };
    const c = cfg[type] || cfg.info;

    el.innerHTML = `
      <div style="display:flex;align-items:flex-start;gap:12px;">
        <span style="font-size:22px;line-height:1.1;">${c.icon}</span>
        <div style="flex:1;">
          <div style="font-weight:800;font-size:12px;letter-spacing:0.1em;color:${c.border};margin-bottom:4px;text-transform:uppercase;">${title}</div>
          <div style="font-size:11.5px;color:#d8ecff;line-height:1.55;white-space:pre-line;">${message}</div>
          <div style="font-size:10px;color:#6ab0d4;margin-top:6px;font-family:'JetBrains Mono',monospace;">${new Date().toLocaleTimeString()} · Automated Dispatch Telemetry</div>
        </div>
        <button onclick="this.parentElement.parentElement.style.display='none'" style="background:none;border:none;color:#8fa3b8;cursor:pointer;font-size:18px;line-height:1;padding:0;">✕</button>
      </div>
    `;
    Object.assign(el.style, {
      display: 'block',
      opacity: '0',
      transition: 'opacity 0.3s ease',
      borderColor: c.border,
      background: c.bg,
      boxShadow: `0 0 28px ${c.border}55, 0 10px 34px rgba(0,0,0,0.7)`
    });
    setTimeout(() => { el.style.opacity = '1'; }, 50);

    clearTimeout(el._t);
    el._t = setTimeout(() => {
      el.style.opacity = '0';
      setTimeout(() => { el.style.display = 'none'; }, 400);
    }, 11000);
  },

  _updateSimUI(state) {
    const s = document.getElementById('sim-start-btn');
    const p = document.getElementById('sim-pause-btn');
    const r = document.getElementById('sim-resume-btn');
    const st = document.getElementById('sim-status-text');
    const dot = document.getElementById('sim-live-dot');
    if (!s) return;

    if (state === 'running') {
      s.style.display = 'none';
      p.style.display = 'flex';
      r.style.display = 'none';
      if (st) { st.textContent = '▶ LIVE'; st.style.color = '#00ff88'; }
      if (dot) dot.style.background = '#00ff88';
    } else if (state === 'rerouting') {
      if (st) { st.textContent = '🔄 REROUTING'; st.style.color = '#ff9500'; }
      if (dot) dot.style.background = '#ff9500';
    } else if (state === 'paused') {
      p.style.display = 'none';
      r.style.display = 'flex';
      if (st) { st.textContent = '⏸ PAUSED'; st.style.color = '#ffcc00'; }
      if (dot) dot.style.background = '#ffcc00';
    } else {
      s.style.display = 'flex';
      p.style.display = 'none';
      r.style.display = 'none';
      if (st) { st.textContent = '⏹ STANDBY'; st.style.color = '#8fa3b8'; }
      if (dot) dot.style.background = '#8fa3b8';
    }
  },

  _updateDashboard() {
    const active = this.vehicles.filter(v => v.status === 'on-route' || v.status === 'rerouting').length;
    const rerouted = this.vehicles.filter(v => v.rerouted).length;
    const delayed = this.vehicles.filter(v => v.status === 'delayed' || v.paused).length;

    [
      ['sim-active-count', active],
      ['sim-rerouted-count', rerouted],
      ['sim-delayed-count', delayed]
    ].forEach(([id, val]) => {
      const e = document.getElementById(id);
      if (e) e.textContent = val;
    });
  }
