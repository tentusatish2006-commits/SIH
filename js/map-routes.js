  _executeReroute(v) {
    const alt = DEMO_ROUTES.guwahati_imphal_alternate;
    v.currentRouteCoords = [...alt.coords];

    if (v.marker) {
      const pos = v.marker.getLatLng();
      let ci = 0, cd = Infinity;
      alt.coords.forEach((c, i) => {
        const d = Math.hypot(c[0] - pos.lat, c[1] - pos.lng);
        if (d < cd) { cd = d; ci = i; }
      });
      v.routeIndex = Math.max(0, Math.min(ci, alt.coords.length - 2));
    } else {
      v.routeIndex = 0;
    }

    v.progress = 0;
    v.rerouted = true;
    v.status = 'on-route';
    v.speed = 46;
    v.roadName = 'GS-1 / NH-6 / NH-37 (Silchar-Jiribam Alternate)';

    if (this.trailLayers[v.id]) {
      this.trailLayers[v.id].setStyle({ color: '#ff9500' });
    }

    this._drawAlternateRouteOverlay();

    setTimeout(() => {
      this._showAlert(
        '✅ MEDICINE VEHICLE REROUTED',
        'Medicine convoy MED-204 rerouted through alternate corridor.\nRoute: Via Shillong → Silchar → Jiribam.\nETA updated: +3h 15m travel time.',
        'success'
      );
    }, 800);

    this._updateSimUI('running');
    this._updateDashboard();
  },

